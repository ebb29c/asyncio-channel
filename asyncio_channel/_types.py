from __future__ import annotations

__all__ = ('AnyChannel', 'BufferProtocol', 'ReadableChannel', 'WritableChannel')

from typing import Any, Awaitable, Protocol


class BufferProtocol(Protocol):
    """Structural type for buffer objects accepted by Channel."""

    maxsize: int

    def empty(self) -> bool: ...
    def full(self) -> bool: ...
    def get(self) -> Awaitable[Any]: ...
    def get_nowait(self) -> Any: ...
    def put(self, item: Any) -> Awaitable[None]: ...
    def put_nowait(self, item: Any) -> None: ...
    def qsize(self) -> int: ...


class ReadableChannel(Protocol):
    """Structural type for the readable side of a channel."""

    def empty(self) -> bool: ...
    def is_closed(self) -> bool: ...
    def closed(self) -> Awaitable[None]: ...
    def item(self, *, timeout: float | None = None) -> Awaitable[bool]: ...
    def poll(self, *, default: Any = None) -> Any: ...
    def take(self, *, timeout: float | None = None, default: Any = None) -> Awaitable[Any]: ...


class WritableChannel(Protocol):
    """Structural type for the writable side of a channel."""

    def full(self) -> bool: ...
    def is_closed(self) -> bool: ...
    def close(self) -> None: ...
    def capacity(self, *, timeout: float | None = None) -> Awaitable[bool]: ...
    def offer(self, x: Any) -> bool: ...
    def put(self, x: Any, *, timeout: float | None = None) -> Awaitable[bool]: ...


class AnyChannel(ReadableChannel, WritableChannel, Protocol):
    """Structural type combining readable and writable channel operations."""
    ...
